set -euo pipefail
IFS=$'\n\t'

# ── Locate the repo ───────────────────────────────────────────────────────────
_THEME_CMD_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
_THEME_LIB_DIR="${_THEME_CMD_DIR}/../../lib"
_THEME_ENGINE_DIR="${_THEME_CMD_DIR}/../../engines/color-engine"
_THEME_ROOT="$(cd "${_THEME_CMD_DIR}/../../.." && pwd)"

# ── Libraries ─────────────────────────────────────────────────────────────────
# Each guards itself, so this is a no-op when the dispatcher already loaded them.
for _lib in colors logger utils template-engine box-renderer table-renderer; do
    [[ -r "${_THEME_LIB_DIR}/${_lib}.sh" ]] && source "${_THEME_LIB_DIR}/${_lib}.sh"
done
unset _lib

# ── Colour engine ─────────────────────────────────────────────────────────────
# In dependency order: oklch/hsl are the maths, contrast and harmonize build on
# them, palette and generate build on those, and wcag-validate sits on top.
for _mod in oklch hsl contrast-check harmonize palette generate extract gradient \
            material-you wcag-validate; do
    [[ -r "${_THEME_ENGINE_DIR}/${_mod}.sh" ]] && source "${_THEME_ENGINE_DIR}/${_mod}.sh"
done
unset _mod

# ─────────────────────────────────────────────────────────────────────────────
# Paths
#
# The catalogue ships with the repo and is read-only in effect — it is
# regenerated by scripts/theme/generate-library.sh, so hand edits are lost. User
# themes live under XDG_DATA_HOME and are searched first, which is what makes
# `ash theme create` + `ash theme apply` work without touching the checkout.
# ─────────────────────────────────────────────────────────────────────────────
THEME_CATALOGUE_DIR="${ASH_THEMES_DIR:-${_THEME_ROOT}/themes}"
THEME_USER_DIR="${ASH_DATA_HOME:-${XDG_DATA_HOME:-$HOME/.local/share}/ash}/themes"
THEME_FAVORITES_FILE="${ASH_DATA_HOME:-${XDG_DATA_HOME:-$HOME/.local/share}/ash}/theme-favorites.json"
THEME_HISTORY_FILE="${ASH_STATE_HOME:-${XDG_STATE_HOME:-$HOME/.local/state}/ash}/theme-history.jsonl"
THEME_CURRENT_FILE="${ASH_CONFIG_HOME:-${XDG_CONFIG_HOME:-$HOME/.config}/ash}/current-theme.json"
THEME_TEMPLATE_DIR="${_THEME_ENGINE_DIR}/templates"
THEME_TRASH_DIR="${ASH_DATA_HOME:-${XDG_DATA_HOME:-$HOME/.local/share}/ash}/themes/.trash"

# Slots in presentation order: surface tones dark→light, then foregrounds, then
# accents. This is the order a reader scans a palette in.
THEME_SLOT_ORDER=(
    crust mantle base surface overlay
    text subtext
    accent mint sky gold rose violet
)

# ─────────────────────────────────────────────────────────────────────────────
# Shared helpers
# ─────────────────────────────────────────────────────────────────────────────

# Resolve a name to a catalogue file. Accepts a slug, a display name in any
# case, or an explicit path. User themes shadow catalogue themes of the same
# slug, so a locally created "nord" wins over the built-in one.
theme::resolve() {
    local want="$1" cand

    [[ -f "$want" ]] && { printf '%s' "$want"; return 0; }

    for cand in "${THEME_USER_DIR}/${want}.json" \
                "${THEME_CATALOGUE_DIR}/${want}.json" \
                "${THEME_CATALOGUE_DIR}/presets/${want}.json"; do
        [[ -f "$cand" ]] && { printf '%s' "$cand"; return 0; }
    done

    # Case-insensitive match on display name, then slug. Covers both
    # directories so a user theme is found by name too.
    local d f slug name
    for d in "$THEME_USER_DIR" "$THEME_CATALOGUE_DIR"; do
        [[ -d "$d" ]] || continue
        for f in "$d"/*.json; do
            [[ -f "$f" ]] || continue
            slug="$(jq -r '.slug // empty' "$f" 2>/dev/null)"
            name="$(jq -r '.name // empty' "$f" 2>/dev/null)"
            if [[ "${slug,,}" == "${want,,}" || "${name,,}" == "${want,,}" ]]; then
                printf '%s' "$f"; return 0
            fi
        done
    done

    return 1
}

# Every theme file, user themes first so they shadow the catalogue.
theme::files() {
    local d f
    for d in "$THEME_USER_DIR" "$THEME_CATALOGUE_DIR"; do
        [[ -d "$d" ]] || continue
        for f in "$d"/*.json; do
            [[ -f "$f" ]] && printf '%s\n' "$f"
        done
    done
}

# slug<TAB>name<TAB>variant<TAB>family<TAB>seed<TAB>path for every theme,
# sorted by family then slug.
#
# One jq pass over the whole set rather than one per file: 361 files spawned as
# 361 processes takes seconds; this takes milliseconds.
theme::index() {
    local -a files=()
    local f
    while IFS= read -r f; do files+=("$f"); done < <(theme::files)
    (( ${#files[@]} )) || return 0

    jq -r --arg p "$PWD" '
        [ (.slug // ""), (.name // ""), (.variant // "dark"), (.family // "other"),
          (.seed // ""), (input_filename) ] | @tsv
    ' "${files[@]}" 2>/dev/null | sort -t$'\t' -k4,4 -k1,1
}

# Load a theme file into any palette nameref. Prefers the engine's loader, which
# understands both the nested document and a bare palette, and falls back to a
# jq read so `show` works from a bare checkout.
theme::load() {
    local file="$1"
    local -n ref="$2"

    if declare -f _ash_palette_load_file >/dev/null 2>&1; then
        _ash_palette_load_file "$file" ref
        return 0
    fi

    local k v
    while IFS=$'\t' read -r k v; do
        [[ -n "$k" ]] && ref["$k"]="$v"
    done < <(jq -r '
        (if has("colors") then .colors else . end)
        | to_entries | map(select(.value | type == "string" and test("^#[0-9a-fA-F]{6}$")))
        | .[] | "\(.key)\t\(.value)"' "$file" 2>/dev/null)
}

# A filled block drawn in the colour itself, so the swatch IS the hex. Returns
# blanks rather than escape codes when colour is off, keeping the column width
# consistent in logs and `--json` output.
theme::swatch() {
    local hex="$1" width="${2:-12}"
    [[ -n "$hex" ]] || { printf '%*s' "$width" ''; return 0; }
    if [[ "${ASH_FLAG_NO_COLOR:-0}" -eq 1 || ! -t 1 ]]; then
        printf '%*s' "$width" ''; return 0
    fi

    local r g b bar
    r=$(( 16#${hex:1:2} )); g=$(( 16#${hex:3:2} )); b=$(( 16#${hex:5:2} ))
    bar="$(printf '%*s' "$width" '' | tr ' ' '█')"
    printf '\033[38;2;%d;%d;%dm%s\033[0m' "$r" "$g" "$b" "$bar"
}

# Is this one of the 13 palette slots?
#
# Written as an explicit loop rather than `[[ " ${THEME_SLOT_ORDER[*]} " == ... ]]`:
# bash joins an array with the FIRST character of IFS, and the dispatcher sets
# IFS=$'\n\t' — so the joined string is newline-separated and no space-delimited
# pattern ever matches. That silently rejected every valid slot name.
theme::is_slot() {
    local want="$1" s
    for s in "${THEME_SLOT_ORDER[@]}"; do
        [[ "$s" == "$want" ]] && return 0
    done
    return 1
}

# Count with correct pluralisation.
theme::plural() {
    local n="$1" one="$2" many="${3:-}"
    if [[ -z "$many" ]]; then
        case "$one" in
            *y) many="${one%y}ies" ;;
            *s|*x|*ch|*sh) many="${one}es" ;;
            *) many="${one}s" ;;
        esac
    fi
    if [[ "$n" == "1" ]]; then printf '%s %s' "$n" "$one"; else printf '%s %s' "$n" "$many"; fi
}

# Write a palette document, preserving metadata. Always writes the nested shape
# so every consumer sees one layout.
theme::save() {
    local file="$1"
    local -n ref="$2"
    local -A meta=()
    shift 2 || true

    # Carry forward any existing metadata, then apply overrides.
    if [[ -f "$file" ]] && jq -e 'type == "object"' "$file" >/dev/null 2>&1; then
        local k v
        while IFS=$'\t' read -r k v; do meta["$k"]="$v"; done < <(
            jq -r 'to_entries
                   | map(select(.value | type == "string"))
                   | .[] | "\(.key)\t\(.value)"' "$file" 2>/dev/null)
    fi

    local pair
    for pair in "$@"; do
        meta["${pair%%=*}"]="${pair#*=}"
    done

    mkdir -p "$(dirname "$file")"

    # Build the colours object, then merge the metadata over it.
    local colors_json
    colors_json="$(ash_palette_render_json ref 2>/dev/null)" || return 1

    local meta_json='{}'
    local key
    for key in "${!meta[@]}"; do
        [[ -n "${meta[$key]}" ]] || continue
        meta_json="$(jq -c --arg k "$key" --arg v "${meta[$key]}" '. + {($k): $v}' <<<"$meta_json")"
    done

    jq -S --argjson c "$colors_json" --argjson m "$meta_json" \
       '$m + {colors: $c}' <<<"{}" > "${file}.tmp" || return 1
    mv "${file}.tmp" "$file"
}

# Record a theme change, so `ash theme history` has something to show.
theme::record() {
    local slug="$1" action="${2:-apply}"
    mkdir -p "$(dirname "$THEME_HISTORY_FILE")" 2>/dev/null || true
    jq -cn --arg slug "$slug" --arg action "$action" \
           --arg at "$(date -Is 2>/dev/null || date)" \
           '{slug: $slug, action: $action, at: $at}' >> "$THEME_HISTORY_FILE" 2>/dev/null || true
}

# Read the currently applied theme slug, if any.
theme::current() {
    [[ -f "$THEME_CURRENT_FILE" ]] || return 1
    jq -r '.slug // empty' "$THEME_CURRENT_FILE" 2>/dev/null
}

# Mark a theme as applied.
theme::set_current() {
    local file="$1" slug="$2"
    mkdir -p "$(dirname "$THEME_CURRENT_FILE")" 2>/dev/null || true
    jq -n --arg slug "$slug" --arg file "$file" \
          --arg at "$(date -Is 2>/dev/null || date)" \
          '{slug: $slug, file: $file, at: $at}' > "$THEME_CURRENT_FILE" 2>/dev/null || true
}

