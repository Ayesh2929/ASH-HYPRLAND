theme::help() {
    ash_banner "🎨 ASH THEME" "catalogue · generation · contrast · store" "80"

    cat <<EOF

${BOLD}${ASH_PRIMARY}USAGE${RST}
  ${ASH_ACCENT}ash theme${RST} <subcommand> [options]

${BOLD}${ASH_PRIMARY}SUBCOMMANDS${RST}
EOF

    local key desc
    for key in "${!THEME_SUBCOMMANDS[@]}"; do
        desc="${THEME_SUBCOMMANDS[$key]#*|}"
        printf '  %s%-16s%s %s\n' "$ASH_ACCENT" "$key" "$RST" "$desc"
    done | sort

    cat <<EOF

${BOLD}${ASH_PRIMARY}EXAMPLES${RST}
  ${ASH_MUTED}# Browse and preview${RST}
  ash theme list --family nord
  ash theme colors nord
  ash theme preview nord

${ASH_MUTED}# Build config files from a theme, and keep a record${RST}
  ash theme apply nord
  ash theme history --limit 10

${ASH_MUTED}# Derive a theme from a wallpaper or from words${RST}
  ash theme wallpaper ~/Pictures/dusk.jpg --apply
  ash theme ai-generate "deep forest at dusk"
  ash theme ai-mood calm

${ASH_MUTED}# Keep a theme and share it${RST}
  ash theme favorite add nord
  ash theme export nord --format base16 --out ~/nord.yaml

${ASH_MUTED}# Keep it honest${RST}
  ash theme validate --all
  ash theme wcag --sweep
  ash theme reset --undo

${BOLD}${ASH_PRIMARY}CATALOGUE${RST}
  ${ASH_MUTED}Built-in : ${THEME_CATALOGUE_DIR}${RST}
  ${ASH_MUTED}User     : ${THEME_USER_DIR}${RST}
  ${ASH_MUTED}Templates: ${THEME_TEMPLATE_DIR}${RST}

EOF
}

# Load a subcommand module by registry key. Returns non-zero, with a message,
# if the module or its function is missing.
#
# Sourced on demand: `ash theme list` should not have to parse the AI and store
# modules. Submodules are libraries, so they define rather than execute.
theme::source_sub() {
    local sub="$1"
    local entry="${THEME_SUBCOMMANDS[$sub]:-}"

    if [[ -z "$entry" ]]; then
        ash_log_error "Unknown subcommand: ${sub}"
        return 1
    fi

    local file="${_THEME_CMD_DIR}/${entry%%|*}"
    if [[ ! -r "$file" ]]; then
        ash_log_error "Subcommand module missing: $(basename "$file")"
        return 1
    fi

    # Already loaded? Then this is a repeat call, not a second definition.
    local fn="theme::${sub//-/_}"
    if declare -F "$fn" >/dev/null 2>&1; then
        return 0
    fi

    # shellcheck source=/dev/null
    source "$file"

    declare -F "$fn" >/dev/null 2>&1 || {
        ash_log_error "Subcommand function not defined: ${fn}"
        return 1
    }
}

theme::main() {
    local sub="${1:-}"; shift || true

    # Resolve aliases before the empty check: `ash theme t` should reach the
    # list, and an unknown word should say so rather than print the help.
    if [[ -n "$sub" && -n "${THEME_ALIASES[$sub]:-}" ]]; then
        sub="${THEME_ALIASES[$sub]}"
    fi

    case "$sub" in
        ""|help|--help|-h) theme::help; return 0 ;;
    esac

    local entry="${THEME_SUBCOMMANDS[$sub]:-}"
    if [[ -z "$entry" ]]; then
        ash_log_error "Unknown subcommand: ${sub}"
        ash_log_info  "Run 'ash theme --help' for the subcommand list"
        return 1
    fi

    theme::source_sub "$sub" || return 1

    local fn="theme::${sub//-/_}"
    if ! declare -F "$fn" >/dev/null 2>&1; then
        ash_log_error "Subcommand function not defined: ${fn}"
        return 1
    fi

    "$fn" "$@"
}

# Executing this file directly still works; sourcing it — which is how the
# dispatcher loads it — must only define the entry point.
if [[ "${BASH_SOURCE[0]}" == "${0}" ]]; then
    theme::main "$@"
fi

ash_cmd_theme() {
    theme::main "$@"
}

# Top-level `ash wcag` entry point — see the ASH_COMMANDS table in ash-cli/ash.
# Only the contrast gate is exposed this way; the rest of the engine is reached
# through `ash theme`.
ash_cmd_wcag() {
    # `ash wcag` is the same code path as `ash theme wcag`, so load the module
    # the same way rather than assuming theme::main has already done it.
    theme::source_sub wcag || return 1
    theme::wcag "$@"
}
